interface ActivityProps {
  seed: number;
  onResult: (r: Result) => void;
  locked: boolean;
}

function usePracticeTree(seed: number, order = 3, count = 9) {
  return useMemo(() => randomTree(order, count, seed), [seed, order, count]);
}

function PredictPath({ seed, onResult, locked }: ActivityProps) {
  const tree = usePracticeTree(seed);
  const target = useMemo(() => randomKeys(1, seed + 7)[0]!, [seed]);
  const [picked, setPicked] = useState<string[]>([]);
  const expected = pathTo(tree, target).map((n) => n.id);

  return (
    <>
      <h2 className="text-heading">Predict the search path for {target}</h2>
      <p className="text-small mt-1">
        Tap the nodes a search visits, from the root down, in order.
      </p>
      <div className="my-4 rounded-lg bg-sky-200">
        <BTreeView
          tree={tree}
          scene
          label="Tree to search"
          onNodeClick={(n) => !locked && setPicked((p) => (p.includes(n.id) ? p : [...p, n.id]))}
          selectedNodeIds={picked}
        />
      </div>
      <div className="flex gap-3">
        <Button variant="outline" onClick={() => setPicked([])} disabled={!picked.length || locked}>
          Clear
        </Button>
        <Button
          disabled={!picked.length || locked}
          onClick={() => {
            const ok = picked.join() === expected.join();
            onResult({
              correct: ok,
              feedback: ok
                ? `At each node you compared ${target} with the keys and took the child between them.`
                : `The search visits ${expected.length} node(s). Compare ${target} with the keys at every node, not just the root.`,
            });
          }}
        >
          Check
        </Button>
      </div>
    </>
  );
}

function WhereDoesItGo({ seed, onResult, locked }: ActivityProps) {
  const tree = usePracticeTree(seed);
  const target = useMemo(() => {
    const rand = seededRandom(seed + 3);
    const existing = new Set<number>();
    const walk = (n: BTreeNode) => {
      n.keys.forEach((k) => existing.add(k));
      n.children.forEach(walk);
    };
    if (tree.root) walk(tree.root);
    let k = 0;
    do k = 1 + Math.floor(rand() * 99);
    while (existing.has(k));
    return k;
  }, [tree, seed]);
  const leaf = pathTo(tree, target).at(-1)!;

  return (
    <>
      <h2 className="text-heading">Where does {target} go?</h2>
      <p className="text-small mt-1">Tap the leaf where {target} is inserted.</p>
      <div className="my-4 rounded-lg bg-sky-200">
        <BTreeView
          tree={tree}
          scene
          label="Tree to insert into"
          newKey={target}
          onNodeClick={(n) => {
            if (locked) return;
            if (!isLeaf(n)) {
              onResult({
                correct: false,
                feedback: 'New keys always go into a leaf, never straight into an internal node.',
              });
              return;
            }
            onResult({
              correct: n.id === leaf.id,
              feedback:
                n.id === leaf.id
                  ? `${target} fits between its neighbours in that leaf.`
                  : `Follow the search for ${target} from the root: it ends at the leaf [${leaf.keys}].`,
            });
          }}
        />
      </div>
    </>
  );
}

/* ---------- Split it yourself (drag and drop, or tap a key then tap a spot) ---------- */

type Slot = 'parent' | 'left' | 'right';

function DraggableKey({
  value,
  selected,
  onTap,
  disabled,
}: {
  value: number;
  selected: boolean;
  onTap: () => void;
  disabled: boolean;
}) {
  const { attributes, listeners, setNodeRef, transform } = useDraggable({
    id: `key-${value}`,
    disabled,
  });
  return (
    <button
      ref={setNodeRef}
      type="button"
      {...listeners}
      {...attributes}
      onClick={onTap}
      aria-pressed={selected}
      aria-label={`Key ${value}${selected ? ', selected' : ''}`}
      style={transform ? { transform: `translate(${transform.x}px, ${transform.y}px)` } : undefined}
      className={cn(
        'font-display shadow-paper-stack-sm rounded-pill grid h-12 w-12 touch-none place-items-center border-4',
        selected ? 'border-yarn bg-highlight text-on-highlight' : 'border-branch bg-node-fill',
      )}
    >
      {value}
    </button>
  );
}

function DropSlot({
  id,
  label,
  keys,
  onTap,
}: {
  id: Slot;
  label: string;
  keys: number[];
  onTap: () => void;
}) {
  const { setNodeRef, isOver } = useDroppable({ id });
  return (
    <div className="flex flex-col items-center gap-2">
      <span className="text-label font-bold">{label}</span>
      <button
        ref={setNodeRef}
        type="button"
        onClick={onTap}
        aria-label={`${label}: ${keys.length ? keys.join(', ') : 'empty'}. Tap to place the selected key.`}
        className={cn(
          'border-ink rounded-pill flex min-h-14 min-w-14 items-center justify-center gap-1 border-2 border-dashed p-1',
          isOver && 'bg-highlight/40',
        )}
      >
        {keys.map((k) => (
          <span
            key={k}
            className="border-branch bg-node-fill font-display rounded-pill grid h-11 w-11 place-items-center border-4"
          >
            {k}
          </span>
        ))}
      </button>
    </div>
  );
}

function SplitItYourself({ seed, onResult, locked }: ActivityProps) {
  const order = seed % 3 === 0 ? 5 : 3;
  const { overflow, parentKey, newKey } = useMemo(() => {
    const keys = randomKeys(order, seed, 60)
      .map((k) => k + 20)
      .sort((a, b) => a - b);
    return { overflow: keys, parentKey: 10 + (seed % 9), newKey: keys[seed % keys.length]! };
  }, [order, seed]);
  const median = overflow[medianIndex(order)]!;
  const [placed, setPlaced] = useState<Record<number, Slot>>({});
  const [selected, setSelected] = useState<number | null>(null);

  const place = (key: number, slot: Slot) => {
    if (locked) return;
    setPlaced((p) => ({ ...p, [key]: slot }));
    setSelected(null);
  };
  const onDragEnd = (e: DragEndEvent) => {
    if (e.over) place(Number(String(e.active.id).replace('key-', '')), e.over.id as Slot);
  };
  const inSlot = (slot: Slot) => overflow.filter((k) => placed[k] === slot);
  const unplaced = overflow.filter((k) => !placed[k]);

  const check = () => {
    const up = inSlot('parent');
    if (up.length === 1 && up[0] === newKey && newKey !== median) {
      onResult({
        correct: false,
        feedback: 'The key that moves up is the middle one after insertion, not the new one.',
      });
      return;
    }
    const ok =
      up.length === 1 &&
      up[0] === median &&
      inSlot('left').every((k) => k < median) &&
      inSlot('right').every((k) => k > median) &&
      unplaced.length === 0;
    onResult({
      correct: ok,
      feedback: ok
        ? `${median} is the middle key, so it moves up next to ${parentKey}. Smaller keys stay left, larger keys go right.`
        : `Only the middle key (${median}) moves up. Keys smaller than it form the left node, larger keys the right node.`,
    });
  };

  return (
    <DndContext onDragEnd={onDragEnd}>
      <h2 className="text-heading">Split the overflowing node</h2>
      <p className="text-small mt-1">
        Inserting {newKey} made this branch overflow (order {order}, room for {order - 1} keys).
        Drag each key to where it belongs after the split, or tap a key and then tap a spot.
      </p>
      <div className="my-5 flex flex-col items-center">
        <div className="bg-danger rounded-pill flex gap-1 p-1.5">
          {overflow.map((k) => (
            <span
              key={k}
              className={cn(
                'bg-node-fill font-display rounded-pill grid h-11 w-11 place-items-center border-4',
                k === newKey ? 'border-yarn' : 'border-branch',
              )}
            >
              {k}
            </span>
          ))}
        </div>
        <span className="text-danger-text text-small mt-1 font-bold">Overflowing branch</span>
      </div>
      <div className="border-ink rounded-lg border-2 border-dashed bg-sky-100 p-5">
        <div className="flex justify-center">
          <DropSlot
            id="parent"
            label={`Moves up to the parent (next to ${parentKey})`}
            keys={inSlot('parent')}
            onTap={() => selected !== null && place(selected, 'parent')}
          />
        </div>
        <div className="mt-4 flex justify-center gap-10">
          <DropSlot
            id="left"
            label="Left node"
            keys={inSlot('left')}
            onTap={() => selected !== null && place(selected, 'left')}
          />
          <DropSlot
            id="right"
            label="Right node"
            keys={inSlot('right')}
            onTap={() => selected !== null && place(selected, 'right')}
          />
        </div>
      </div>
      <div className="mt-4 flex flex-wrap items-center gap-3">
        <span className="text-label font-bold">Keys to place:</span>
        {unplaced.map((k) => (
          <DraggableKey
            key={k}
            value={k}
            selected={selected === k}
            disabled={locked}
            onTap={() => setSelected(k)}
          />
        ))}
        <Button variant="outline" size="sm" onClick={() => setPlaced({})} disabled={locked}>
          Reset
        </Button>
        <Button size="sm" onClick={check} disabled={locked || unplaced.length > 0}>
          Check
        </Button>
      </div>
    </DndContext>
  );
}

