function ValidOrNot({ seed, onResult, locked }: ActivityProps) {
  const item = useMemo<QuizItem>(() => {
    const tree = randomTree(3, 7, seed);
    let spec = toSpec(tree) as NodeSpec;
    const rand = seededRandom(seed + 11);
    if (rand() < 0.6 && spec.children) {
      // Break one rule on purpose.
      spec = structuredClone(spec);
      const leaf = spec.children![0]!.children?.[0] ?? spec.children![0]!;
      if (rand() < 0.5) leaf.keys.push(leaf.keys.at(-1)! + 1, leaf.keys.at(-1)! + 2);
      else leaf.keys[0] = (spec.keys.at(-1) ?? 0) + 50;
      leaf.keys.sort((a, b) => a - b);
    }
    const v = validate(fromSpec(3, spec));
    return {
      id: `valid-${seed}`,
      objective: 'O2',
      type: 'valid-or-not',
      order: 3,
      prompt: 'Is this a valid order-3 B-tree? If not, which rule does it break?',
      tree: spec,
      valid: v.valid,
      brokenRule: v.violations[0]?.rule,
      hints: [],
    };
  }, [seed]);
  const [answer, setAnswer] = useState<Answer | null>(null);
  return (
    <QuestionCard
      item={item}
      answer={answer}
      locked={locked}
      onSubmit={(_c, a) => {
        setAnswer(a);
        onResult(a);
      }}
    />
  );
}
