type ActivityId = (typeof ACTIVITIES)[number]['id'];

const EXERCISES_PER_ACTIVITY = 4;

interface Result {
  correct: boolean;
  feedback: string;
}

/** Ids and keys of the nodes a search for `key` visits, root first (used for marking). */
function pathTo(tree: BTree, key: number): { id: string; keys: string }[] {
  return search(tree, key)
    .steps.filter((s) => s.kind === 'visit')
    .map((s) => ({ id: s.nodeIds[0]!, keys: String(s.params.keys) }));
}

/** Screen 06: guided practice. Every item is generated by the engine, so students never run out (FR9). */
